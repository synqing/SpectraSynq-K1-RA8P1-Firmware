#!/usr/bin/env python3
"""Generate k1_poly24's Kaiser window table offline (lane P4 correction 2).

The window depends only on the tap count, phase count and beta, never on the measured
source rate, so it is tabulated here instead of on the device. The device then designs
only the rate-dependent sinc at rate lock (P4 review F3: the on-device Bessel/sinf design
made the longest capture poll 8.66 M cycles, above one 7.15 ms PDM slot).

  gen_poly24_window.py            write platform/ra8p1/k1_poly24_window.h
  gen_poly24_window.py --check    exit 1 if the committed header differs from the formula
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "platform/ra8p1/k1_poly24_window.h"
TAPS, PHASES, BETA = 96, 128, 7.0
TOLERANCE = 1e-6


def window() -> np.ndarray:
    """w[p][j] for tap j at phase mu = p / PHASES, the same geometry as k1_poly24_design."""
    half = TAPS * 0.5
    p = np.arange(PHASES + 1)[:, None] / PHASES
    j = np.arange(TAPS)[None, :]
    d = j - (half - 1.0) - p
    arg = 1.0 - (d / half) ** 2
    return np.where(arg > 0.0, np.i0(BETA * np.sqrt(np.clip(arg, 0.0, None))) / np.i0(BETA), 0.0)


def render(w: np.ndarray) -> str:
    rows = []
    for row in w.astype(np.float32):
        cells = ", ".join(f"{float(v):.9e}f" for v in row)
        rows.append(f"    {{{cells}}}")
    return (
        "/* GENERATED by scripts/gen_poly24_window.py -- do not edit.\n"
        f"   Kaiser window, beta {BETA}, {TAPS} taps, {PHASES + 1} phase rows (mu = p/{PHASES}).\n"
        "   Rate-independent; k1_poly24_design multiplies it by the measured-rate sinc. */\n"
        "#pragma once\n\n"
        f"#define K1_POLY24_WINDOW_TAPS {TAPS}u\n"
        f"#define K1_POLY24_WINDOW_PHASES {PHASES}u\n\n"
        f"static const float k1_poly24_window[{PHASES + 1}][{TAPS}] = {{\n"
        + ",\n".join(rows) + "\n};\n"
    )


def parse(text: str) -> np.ndarray:
    body = text.split("= {", 1)[1].rsplit("};", 1)[0]
    values = [float(tok.strip().rstrip("f")) for tok in body.replace("{", " ").replace("}", " ").split(",")
              if tok.strip()]
    return np.array(values, dtype=np.float64).reshape(PHASES + 1, TAPS)


def check(path: Path = HEADER) -> list[str]:
    problems = []
    try:
        table = parse(path.read_text())
    except Exception as exc:  # malformed or missing header is a failure, not a pass
        return [f"cannot parse {path}: {exc}"]
    err = float(np.max(np.abs(table - window())))
    if err > TOLERANCE:
        problems.append(f"window table differs from the Kaiser formula: max |error| {err:.3e} > {TOLERANCE}")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--header", type=Path, default=HEADER)
    a = ap.parse_args()
    if a.check:
        problems = check(a.header)
        for p in problems:
            print("FAIL:", p)
        print("PASS" if not problems else "")
        return 1 if problems else 0
    a.header.write_text(render(window()))
    print(f"wrote {a.header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
