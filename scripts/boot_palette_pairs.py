#!/usr/bin/env python3
"""Generate the Titan's random boot palette pairs from the frozen catalogue.

Captain, 15 Oct 2026: randomise the start-up palettes, and (earlier, same day)
the two edges must never use the same colour family.

Rule, written before the list was generated:
- Sample each palette's stops at 256 positions (linear, as stored).
- Weight each sample by chroma (max - min of RGB). Hue is the chroma-weighted
  circular mean; coverage is the number of 60-degree hue sextants holding at
  least 10 % of the chroma weight.
- Eligible: mean chroma >= 60 of 255 (not washed out); at most 30 % of samples
  darker than 10 % of the palette's peak (not mostly black); coverage <= 3
  sextants (no rainbow palettes, charter: no rainbow defaults).
- Warm: mean hue in [300, 360) or [0, 70) degrees (magenta, red, orange, amber).
  Cool: mean hue in [90, 270) (green, cyan, blue, violet). Others stay out.
- Purity (added after the lane owner looked at the first swatch sheet, which let
  in palettes holding both families, e.g. Sunset_Real ending in blue and
  Blue_Cyan_Yellow ending in yellow): at least 90 % of the chroma weight must lie
  inside the palette's own family range.
- A pair is one warm and one cool eligible palette whose mean hues differ by at
  least 120 degrees. Which edge gets the warm one is a separate random bit.

  python3 scripts/boot_palette_pairs.py [--check]   # --check: fail if the header is stale
"""
from __future__ import annotations

import argparse
import colorsys
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "src/k1/core/visual/product_palette_data.cpp"
HEADER = ROOT / "src/k1/core/visual/boot_palette_pairs.h"
FIGURE = ROOT / "docs/evidence/P6/boot-palettes/pairs.png"


def palettes() -> list[dict]:
    text = DATA.read_text()
    stops = {}
    for m in re.finditer(r"constexpr ProductPaletteStop kStops(\d+)\[\] = \{(.*?)\};", text, re.S):
        stops[int(m.group(1))] = [(int(p), (int(r), int(g), int(b)))
                                  for p, r, g, b in re.findall(r"\{(\d+)U, \{(\d+)U, (\d+)U, (\d+)U\}\}", m.group(2))]
    out = []
    for m in re.finditer(r'\{(\d+)U, "([^"]+)", kStops(\d+), (\d+)U', text):
        out.append({"id": int(m.group(1)), "name": m.group(2), "stops": stops[int(m.group(3))]})
    return out


def sample(st: list) -> list[tuple[float, float, float]]:
    res = []
    for x in range(256):
        lo = max((s for s in st if s[0] <= x), key=lambda s: s[0], default=st[0])
        hi = min((s for s in st if s[0] >= x), key=lambda s: s[0], default=st[-1])
        f = 0.0 if hi[0] == lo[0] else (x - lo[0]) / (hi[0] - lo[0])
        res.append(tuple(lo[1][i] + f * (hi[1][i] - lo[1][i]) for i in range(3)))
    return res


def describe(p: dict) -> dict:
    px = sample(p["stops"])
    chroma = [max(c) - min(c) for c in px]
    value = [max(c) for c in px]
    peak = max(value) or 1.0
    sx = sy = wsum = 0.0
    sext = [0.0] * 6
    warm_w = cool_w = 0.0
    for c, w in zip(px, chroma):
        if w <= 0:
            continue
        h = colorsys.rgb_to_hsv(*(v / 255 for v in c))[0] * 360
        sx += w * math.cos(math.radians(h)); sy += w * math.sin(math.radians(h)); wsum += w
        sext[int(h // 60) % 6] += w
        if h >= 300 or h < 70:
            warm_w += w
        elif 90 <= h < 270:
            cool_w += w
    hue = math.degrees(math.atan2(sy, sx)) % 360 if wsum else 0.0
    coverage = sum(1 for s in sext if wsum and s / wsum >= 0.10)
    dark = sum(1 for v in value if v < 0.10 * peak) / len(value)
    mean_chroma = sum(chroma) / len(chroma)
    family = "warm" if (hue >= 300 or hue < 70) else "cool" if 90 <= hue < 270 else "other"
    purity = (warm_w if family == "warm" else cool_w if family == "cool" else 0.0) / wsum if wsum else 0.0
    eligible = mean_chroma >= 60 and dark <= 0.30 and coverage <= 3 and family != "other" and purity >= 0.90
    return {**p, "value": p["id"] + 1, "hue": hue, "coverage": coverage, "dark": dark, "purity": purity,
            "chroma": mean_chroma, "family": family, "eligible": eligible, "px": px}


def pairs(desc: list[dict]) -> list[tuple[dict, dict]]:
    warm = [d for d in desc if d["eligible"] and d["family"] == "warm"]
    cool = [d for d in desc if d["eligible"] and d["family"] == "cool"]
    out = []
    for w in warm:
        for c in cool:
            gap = abs((w["hue"] - c["hue"] + 180) % 360 - 180)
            if gap >= 120:
                out.append((w, c))
    return out


def header(pp: list[tuple[dict, dict]]) -> str:
    rows = "\n".join(f"    {{{w['value']}U, {c['value']}U}},  // {w['name']} / {c['name']}" for w, c in pp)
    return f"""#pragma once
// Generated by scripts/boot_palette_pairs.py from the frozen palette catalogue; do not edit.
// Each pair is {{warm, cool}} palette values (1-44, renderer index = value - 1).
// Captain, 15 Oct 2026: random start-up palettes; the two edges never share a colour family.
#include <array>
#include <cstdint>

namespace k1::core::visual {{

struct BootPalettePair final {{
  std::uint8_t warm;
  std::uint8_t cool;
}};

inline constexpr std::array<BootPalettePair, {len(pp)}> kBootPalettePairs{{{{
{rows}
}}}};

}}  // namespace k1::core::visual
"""


def figure(pp: list[tuple[dict, dict]], desc: list[dict]) -> None:
    """Eligible palettes as two columns (warm, cool) for the eye check, plus the excluded ones."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    groups = [("warm", [d for d in desc if d["eligible"] and d["family"] == "warm"]),
              ("cool", [d for d in desc if d["eligible"] and d["family"] == "cool"]),
              ("excluded", [d for d in desc if not d["eligible"]])]
    rows = max(len(g) for _, g in groups)
    fig, axes = plt.subplots(rows, 3, figsize=(13, 0.32 * rows + 0.8))
    for col, (title, g) in enumerate(groups):
        axes[0, col].set_title(f"{title} ({len(g)})", fontsize=9)
        for r in range(rows):
            ax = axes[r, col]
            ax.set_xticks([]); ax.set_yticks([])
            if r < len(g):
                d = g[r]
                ax.imshow(np.array([d["px"]], dtype=float) / 255, aspect="auto")
                ax.set_ylabel(f"{d['value']} {d['name'][:22]}", rotation=0, ha="right", va="center", fontsize=6)
            else:
                ax.axis("off")
    fig.suptitle(f"Boot palette families: any warm + any cool >= 120 deg apart = {len(pp)} pairs", fontsize=10)
    fig.tight_layout()
    fig.savefig(FIGURE, dpi=110)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    desc = [describe(p) for p in palettes()]
    if len(desc) != 44:
        raise SystemExit(f"REFUSED: expected 44 palettes, parsed {len(desc)}")
    pp = pairs(desc)
    text = header(pp)
    if a.check:
        ok = HEADER.exists() and HEADER.read_text() == text
        print("header up to date" if ok else "header STALE")
        return 0 if ok else 1
    HEADER.write_text(text)
    figure(pp, desc)
    for d in desc:
        print(f"{d['value']:2d} {d['name'][:30]:30s} hue {d['hue']:5.1f} cov {d['coverage']} dark {d['dark']:.2f} "
              f"chroma {d['chroma']:5.1f} purity {d['purity']:.2f} {d['family']:5s} {'ELIGIBLE' if d['eligible'] else '-'}")
    print(f"{len(pp)} pairs ->", HEADER.relative_to(ROOT), "and", FIGURE.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
